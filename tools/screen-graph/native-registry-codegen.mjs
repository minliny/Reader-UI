function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function chunks(value, size = 8_000) {
  const codePoints = Array.from(value);
  const result = [];
  for (let index = 0; index < codePoints.length; index += size) {
    result.push(codePoints.slice(index, index + size).join(""));
  }
  return result;
}

function quotedChunks(value, indent, transform = (literal) => literal) {
  return chunks(value)
    .map((chunk) => `${indent}${transform(JSON.stringify(chunk))},`)
    .join("\n");
}

function arktsArray(values, type, name) {
  return `const ${name}: ${type}[] = [\n${values.map((value) => `  ${JSON.stringify(value)},`).join("\n")}\n]`;
}

function walkComponents(components, visit) {
  for (const component of components) {
    visit(component);
    walkComponents(component.children, visit);
  }
}

export function validateNativeRegistryGeneration(graph, inputs) {
  const canonicalRoutes = inputs.routeSchema.properties.id.enum;
  const canonicalComponents = inputs.viewStateSchema.$defs.Component.properties.type.enum;
  const canonicalEvents = inputs.uiEventSchema.properties.type.enum;
  const canonicalVariantCount = inputs.viewStateFixtures.length;
  const routeSet = new Set(canonicalRoutes);
  const componentSet = new Set(canonicalComponents);
  const eventSet = new Set(canonicalEvents);

  assert(
    graph.routes.length === canonicalRoutes.length,
    `native registry requires ${canonicalRoutes.length} routes, got ${graph.routes.length}`,
  );
  assert(
    JSON.stringify(graph.routes.map((route) => route.routeId)) === JSON.stringify(canonicalRoutes),
    "native registry RouteId set/order must exactly match route.schema.json",
  );
  assert(routeSet.size === canonicalRoutes.length, "native registry canonical RouteId set contains duplicates");
  assert(
    JSON.stringify(graph.componentCatalog.map((entry) => entry.type)) === JSON.stringify(canonicalComponents),
    "native registry ComponentType catalog must exactly match view-state.schema.json",
  );
  assert(componentSet.size === canonicalComponents.length, "native registry canonical ComponentType set contains duplicates");
  assert(eventSet.size === canonicalEvents.length, "native registry canonical UiEvent set contains duplicates");

  let variants = 0;
  let components = 0;
  let bindings = 0;
  let stateEventEvidence = 0;
  for (const route of graph.routes) {
    assert(routeSet.has(route.routeId), `native registry has unknown RouteId ${route.routeId}`);
    variants += route.variants.length;
    for (const variant of route.variants) {
      for (const component of variant.components) {
        walkComponents([component], (node) => {
          components += 1;
          assert(componentSet.has(node.type), `native registry has unknown ComponentType ${node.type}`);
          assert(Array.isArray(node.stateAuthorities) && node.stateAuthorities.length > 0, `native registry component ${node.id} has no state authority`);
          assert(["contract-tree", "host-composite"].includes(node.compositionMode), `native registry component ${node.id} has invalid composition mode`);
          for (const binding of node.bindings) {
            bindings += 1;
            assert(typeof binding.target === "string" && binding.target.length > 0, `native registry binding ${binding.event} has no target`);
            assert(eventSet.has(binding.event), `native registry has unknown UiEvent binding ${binding.event}`);
          }
          for (const evidence of node.stateEventEvidence) {
            stateEventEvidence += 1;
            assert(eventSet.has(evidence.event), `native registry has unknown state UiEvent evidence ${evidence.event}`);
          }
        });
      }
    }
  }
  assert(
    variants === canonicalVariantCount,
    `native registry requires ${canonicalVariantCount} variants, got ${variants}`,
  );

  return {
    routes: graph.routes.length,
    variants,
    components,
    bindings,
    stateEventEvidence,
    componentTypes: canonicalComponents.length,
    eventTypes: canonicalEvents.length,
  };
}

