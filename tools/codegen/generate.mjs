// --- 工具函数 ---
function readJson(p) {
  return JSON.parse(readFileSync(p, "utf8"));
}

function toPascalCase(s) {
  // 把 kebab-case / snake_case / dotted.name 转为 PascalCase
  return s
    .replace(/[-_.]+/g, " ")
    .replace(/\s+(.)/g, (_, c) => c.toUpperCase())
    .replace(/^(.)/, (_, c) => c.toUpperCase())
    .replace(/\s+/g, "");
}

function toCamelCase(s) {
  const p = toPascalCase(s);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

function stringLiteral(value) {
  return JSON.stringify(String(value));
}

function swiftMotionIdCase(id) {
  return id.replace(/[^A-Za-z0-9_]/g, "_");
}

function swiftEasingCase(easing) {
  return easing === "none" ? "noneValue" : easing.replace(/-/g, "_");
}

function kotlinCase(value) {
  return toPascalCase(String(value)).replace(/[^A-Za-z0-9_]/g, "_");
}

function reducedMotionInfo(item) {
  const guardRules = Array.isArray(item.guardRules) ? item.guardRules : [];
  const sourceRule = guardRules.find((rule) => String(rule).startsWith("reducedMotion:")) || null;
  return {
    forceZeroDuration: sourceRule === "reducedMotion:forceZeroDuration" || item.durationMs === 0,
    directManipulation: guardRules.some((rule) =>
      String(rule).startsWith("dragMustFollowFinger:") || String(rule).startsWith("releaseToSnap:")
    ),
    sourceRule,
  };
}

function swiftStringArray(values) {
  return `[${values.map(stringLiteral).join(", ")}]`;
}

function kotlinStringList(values) {
  return values.length > 0 ? `listOf(${values.map(stringLiteral).join(", ")})` : "emptyList()";
}

function arkTsStringArray(values) {
  return `[${values.map(stringLiteral).join(", ")}]`;
}

// --- 加载 schema 与 fixtures ---
function loadSchema(name) {
  return readJson(join(CONTRACTS_DIR, `${name}.schema.json`));
}

function loadFixtures(name) {
  const p = join(CONTRACTS_DIR, "fixtures", `${name}.fixtures.json`);
  if (!existsSync(p)) return [];
  return readJson(p);
}

// 提取 enum 值（schema 中 properties.<key>.enum）。无 enum 时返回 undefined 便于 fallback。
function extractEnum(schema, key) {
  const node = key.split(".").reduce((acc, k) => (acc ? acc[k] : undefined), schema.properties);
  if (!node) return undefined;
  if (Array.isArray(node.enum)) {
    const filtered = node.enum.filter((v) => v !== null);
    return filtered.length > 0 ? filtered : undefined;
  }
  return undefined;
}

