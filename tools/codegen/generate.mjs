function genKotlinEnum(name, values, valueTransform = (v) => v) {
  const cases = values.map((v) => {
    const ident = toPascalCase(String(v)).replace(/[^A-Za-z0-9_]/g, "_");
    return `    @SerialName("${v}")\n    ${ident}`;
  });
  return `@Serializable
enum class ${name} {
${cases.join(",\n")}
}`;
}

