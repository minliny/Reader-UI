// 将 schema enum 值转为合法 Swift case 名。overrides 处理关键字冲突（如 "default"）。
function swiftEnumCaseName(value, overrides) {
  if (overrides && overrides[value]) return overrides[value];
  if (value === "default") return "defaultValue"; // Swift keyword
  return toCamelCase(value).replace(/[^A-Za-z0-9_]/g, "_");
}

function genSwiftStringEnum(name, values, overrides) {
  const cases = values.map((v) => {
    const caseName = swiftEnumCaseName(v, overrides);
    return caseName === v ? `    case ${caseName}` : `    case ${caseName} = "${v}"`;
  });
  return `public enum ${name}: String, Codable, CaseIterable, Sendable {
${cases.join("\n")}
}`;
}

