#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const outputPath = path.join(root, "frontend-demo-optimized", "motion-contract-registry.js");
const check = process.argv.includes("--check");

if (process.argv.slice(2).some((argument) => argument !== "--check")) {
  console.error("[demo-motion-registry] unknown argument");
  process.exit(2);
}

function readJson(relativePath) {
  return JSON.parse(fs.readFileSync(path.join(root, relativePath), "utf8"));
}

function serialize(value) {
  return JSON.stringify(value, null, 2);
}

const version = readJson("contracts/VERSION.json").version;
const motionSchema = readJson("contracts/motion.schema.json");
const specs = readJson("contracts/fixtures/motion.fixtures.json");
const policies = readJson("contracts/fixtures/motion-policy.fixtures.json").filter((policy) => policy.id);
const routeShells = Object.fromEntries(
  readJson("contracts/fixtures/route.fixtures.json")
    .filter((route) => route.id && route.shell)
    .map((route) => [route.id, route.shell]),
);

const canonicalIds = motionSchema.properties.id.enum;
const fixtureIds = specs.map((spec) => spec.id);
if (
  specs.length !== canonicalIds.length ||
  new Set(fixtureIds).size !== fixtureIds.length ||
  canonicalIds.some((motionId) => !fixtureIds.includes(motionId))
) {
  throw new Error("motion fixtures must exactly match the canonical MotionId set");
}

const output = `// AUTO-GENERATED by tools/motion/generate-demo-motion-registry.mjs. DO NOT EDIT.
// Source: contracts/fixtures/motion.fixtures.json + motion-policy.fixtures.json + route.fixtures.json
(function attachReaderMotionContractRegistry(window) {
  "use strict";

  const VERSION = ${JSON.stringify(version)};
  const MOTION_SPECS = ${serialize(specs)};
  const MOTION_POLICIES = ${serialize(policies)};
  const ROUTE_SHELLS = ${serialize(routeShells)};
  const MATCH_FIELDS = Object.freeze([
    "fromRoute",
    "toRoute",
    "fromShell",
    "toShell",
    "operation",
    "sourceRole",
    "targetRole",
    "containerRole",
    "reducedMotion"
  ]);

  function deepFreeze(value) {
    if (!value || typeof value !== "object" || Object.isFrozen(value)) return value;
    Object.values(value).forEach(deepFreeze);
    return Object.freeze(value);
  }

  deepFreeze(MOTION_SPECS);
  deepFreeze(MOTION_POLICIES);
  deepFreeze(ROUTE_SHELLS);

  const specById = new Map(MOTION_SPECS.map((spec) => [spec.id, spec]));
  const sortedPolicies = MOTION_POLICIES
    .map((policy, index) => ({ policy, index }))
    .sort((left, right) => {
      if (left.policy.priority !== right.policy.priority) {
        return right.policy.priority - left.policy.priority;
      }
      const leftSpecificity = MATCH_FIELDS.filter((field) => left.policy.match[field] !== undefined).length;
      const rightSpecificity = MATCH_FIELDS.filter((field) => right.policy.match[field] !== undefined).length;
      return rightSpecificity - leftSpecificity || left.index - right.index;
    })
    .map((entry) => entry.policy);

  function specFor(motionId) {
    return specById.get(String(motionId || ""));
  }

  function routeShell(routeId) {
    return ROUTE_SHELLS[String(routeId || "")];
  }

  function matches(policyMatch, request) {
    return MATCH_FIELDS.every((field) => (
      policyMatch[field] === undefined || policyMatch[field] === request[field]
    ));
  }

  function resolveMotionWithDiagnostic(input) {
    const request = Object.assign({}, input || {});
    if (request.fromShell === undefined && request.fromRoute !== undefined) {
      request.fromShell = routeShell(request.fromRoute);
    }
    if (request.toShell === undefined && request.toRoute !== undefined) {
      request.toShell = routeShell(request.toRoute);
    }
    const policy = sortedPolicies.find((candidate) => matches(candidate.match, request));
    return policy
      ? Object.freeze({ motionId: policy.motionId, policyId: policy.id })
      : Object.freeze({ diagnostic: "motion.policy.no-match" });
  }

  function resolveMotion(request) {
    return resolveMotionWithDiagnostic(request).motionId;
  }

  window.ReaderMotionContractRegistry = Object.freeze({
    version: VERSION,
    specs: MOTION_SPECS,
    policies: MOTION_POLICIES,
    routeShells: ROUTE_SHELLS,
    specFor,
    routeShell,
    resolveMotion,
    resolveMotionWithDiagnostic
  });
})(window);
`;

if (check) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error("[demo-motion-registry] DRIFT frontend-demo-optimized/motion-contract-registry.js");
    process.exit(1);
  }
  console.log(`[demo-motion-registry] PASS specs=${specs.length} policies=${policies.length}`);
} else {
  const temporaryPath = `${outputPath}.${process.pid}.tmp`;
  fs.writeFileSync(temporaryPath, output);
  fs.renameSync(temporaryPath, outputPath);
  console.log(`[demo-motion-registry] WROTE specs=${specs.length} policies=${policies.length}`);
}
