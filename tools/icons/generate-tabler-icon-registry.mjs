#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const assetRoot = path.join(root, "frontend-demo-optimized", "asset-library");
const mapPath = path.join(assetRoot, "tabler-icon-map.json");
const outputPath = path.join(assetRoot, "icons.js");

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function assertSortedUnique(values, label) {
  const sorted = [...values].sort((left, right) => left.localeCompare(right, "en"));
  if (new Set(values).size !== values.length) throw new Error(`${label} contains duplicates`);
  if (values.some((value, index) => value !== sorted[index])) throw new Error(`${label} must be sorted`);
}

function compactSvg(rawSvg, { semantic, upstream, variant, strokeWidth }) {
  let svg = rawSvg.trim();
  if (!svg.startsWith("<svg") || !svg.endsWith("</svg>")) {
    throw new Error(`invalid SVG for ${semantic}/${variant}`);
  }
  if (!svg.includes('viewBox="0 0 24 24"')) {
    throw new Error(`unexpected viewBox for ${semantic}/${variant}`);
  }

  svg = svg
    .replace(/<!--[^]*?-->/g, "")
    .replace(/class="[^"]*"/, 'class="asset-icon"')
    .replace(/\s+/g, " ")
    .replace(/> </g, "><")
    .replace(/\s+\/>/g, " />")
    .trim();

  if (variant === "outline") {
    svg = svg.replace(/stroke-width="[^"]+"/, `stroke-width="${strokeWidth}"`);
  }

  const inlinePaint = variant === "outline"
    ? `fill:none;stroke:currentColor;stroke-width:${strokeWidth};stroke-linecap:round;stroke-linejoin:round`
    : "fill:currentColor;stroke:none";
  svg = svg.replace("<svg ", `<svg style="${inlinePaint}" `);

  return svg.replace(
    "<svg ",
    `<svg data-icon-source="tabler-${upstream}" data-icon-variant="${variant}" `,
  );
}

export function buildRegistry() {
  const manifest = readJson(mapPath);
  const semantics = Object.keys(manifest.semantics);
  const filledSemantics = [...manifest.filledSemantics];
  assertSortedUnique(semantics, "semantic icon names");

  const vendorRoot = path.join(
    assetRoot,
    "icons",
    "tabler",
    manifest.source.version,
  );

  const outlines = {};
  for (const semantic of semantics) {
    const upstream = manifest.semantics[semantic];
    const sourcePath = path.join(vendorRoot, "outline", `${upstream}.svg`);
    if (!fs.existsSync(sourcePath)) throw new Error(`missing outline source: ${sourcePath}`);
    outlines[semantic] = compactSvg(fs.readFileSync(sourcePath, "utf8"), {
      semantic,
      upstream,
      variant: "outline",
      strokeWidth: manifest.geometry.outlineStrokeWidth,
    });
  }

  const filled = {};
  for (const semantic of filledSemantics) {
    const upstream = manifest.semantics[semantic];
    if (!upstream) throw new Error(`filled semantic is not registered: ${semantic}`);
    const sourcePath = path.join(vendorRoot, "filled", `${upstream}.svg`);
    if (!fs.existsSync(sourcePath)) throw new Error(`missing filled source: ${sourcePath}`);
    filled[semantic] = compactSvg(fs.readFileSync(sourcePath, "utf8"), {
      semantic,
      upstream,
      variant: "filled",
      strokeWidth: manifest.geometry.outlineStrokeWidth,
    });
  }

  const source = JSON.stringify({
    package: manifest.source.package,
    version: manifest.source.version,
    license: manifest.source.license,
    homepage: manifest.source.homepage,
    outlineStrokeWidth: manifest.geometry.outlineStrokeWidth,
    figmaMasterSize: manifest.geometry.figmaMasterSize,
  }, null, 2).replace(/^/gm, "    ");
  const mapping = JSON.stringify(manifest.semantics, null, 2).replace(/^/gm, "    ");

  const objectLines = (entries) => Object.entries(entries)
    .map(([name, svg]) => `    ${JSON.stringify(name)}: ${JSON.stringify(svg)}`)
    .join(",\n");

  return `// Generated by tools/icons/generate-tabler-icon-registry.mjs. Do not hand-edit.\n` +
`// Source: @tabler/icons ${manifest.source.version} (${manifest.source.license}).\n` +
`(function attachReaderAssetIcons(window) {\n` +
`  "use strict";\n\n` +
`  const source = Object.freeze(\n${source}\n  );\n\n` +
`  const mapping = Object.freeze(\n${mapping}\n  );\n\n` +
`  const icons = Object.freeze({\n${objectLines(outlines)}\n  });\n\n` +
`  const filledIcons = Object.freeze({\n${objectLines(filled)}\n  });\n\n` +
`  function safeAttribute(value) {\n` +
`    return String(value == null ? "" : value).replace(/["<>]/g, "");\n` +
`  }\n\n` +
`  function decorate(svg, name, className, variant) {\n` +
`    return svg\n` +
`      .replace('class="asset-icon"', \`class="\${safeAttribute(className || "asset-icon")}"\`)\n` +
`      .replace("<svg ", \`<svg data-icon-name="\${safeAttribute(name)}" data-reader-icon-variant="\${variant}" \`);\n` +
`  }\n\n` +
`  function resolve(name, variant) {\n` +
`    const collection = variant === "filled" ? filledIcons : icons;\n` +
`    if (!Object.prototype.hasOwnProperty.call(collection, name)) {\n` +
`      console.error(\`[ReaderAssetIcons] Unknown \${variant} icon: \${String(name)}\`);\n` +
`      return "";\n` +
`    }\n` +
`    return collection[name];\n` +
`  }\n\n` +
`  window.ReaderAssetIcons = Object.freeze({\n` +
`    source,\n` +
`    mapping,\n` +
`    icons,\n` +
`    filledIcons,\n` +
`    names: Object.freeze(Object.keys(icons)),\n` +
`    filledNames: Object.freeze(Object.keys(filledIcons)),\n` +
`    renderIcon(name, className, variant = "outline") {\n` +
`      const normalizedVariant = variant === "filled" ? "filled" : "outline";\n` +
`      const svg = resolve(name, normalizedVariant);\n` +
`      return svg ? decorate(svg, name, className, normalizedVariant) : "";\n` +
`    },\n` +
`    has(name, variant = "outline") {\n` +
`      const collection = variant === "filled" ? filledIcons : icons;\n` +
`      return Object.prototype.hasOwnProperty.call(collection, name);\n` +
`    }\n` +
`  });\n` +
`})(window);\n`;
}

const output = buildRegistry();
if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== output) {
    console.error("[tabler-icons] DRIFT frontend-demo-optimized/asset-library/icons.js");
    process.exit(1);
  }
  console.log("[tabler-icons] PASS generated registry is current");
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`[tabler-icons] WROTE ${path.relative(root, outputPath)}`);
}
