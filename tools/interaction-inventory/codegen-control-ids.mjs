#!/usr/bin/env node
// R1.1 · Three-layer identity codegen (entityKey + controlKey + controlId)
//
// Reads tools/interaction-inventory/generated/control-id-registry.json and
// emits per-platform/per-consumer codegen artifacts:
//   - control-identity.generated.ts: TypeScript module exporting the registry.
//   - control-dom-selectors.generated.json: DOM selector map grouped by route.
//   - screengraph-binding.generated.json: ScreenGraph binding map (sorted).
//
// Usage:
//   node tools/interaction-inventory/codegen-control-ids.mjs --write
//   node tools/interaction-inventory/codegen-control-ids.mjs --check
//
// Reproducibility: outputs are deterministic given the registry input.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import {
  REPO_ROOT,
  CONTROL_ID_REGISTRY_PATH,
} from "./interaction-inventory-lib.mjs";
import { formatJson } from "../screen-graph/screen-graph-lib.mjs";

const CODEGEN_OUTPUT_PATHS = Object.freeze({
  typescriptTypes: "tools/interaction-inventory/generated/control-identity.generated.ts",
  domSelectors: "tools/interaction-inventory/generated/control-dom-selectors.generated.json",
  screenGraphBindings: "tools/interaction-inventory/generated/screengraph-binding.generated.json",
});

function readJson(relativePath) {
  return JSON.parse(readFileSync(join(REPO_ROOT, relativePath), "utf8"));
}

function stringifyConst(value) {
  return JSON.stringify(value);
}

function buildTypescriptArtifact(registry) {
  const lines = [];
  lines.push("// AUTO-GENERATED by tools/interaction-inventory/codegen-control-ids.mjs");
  lines.push("// Source: tools/interaction-inventory/generated/control-id-registry.json");
  lines.push("// A2 · Control Identity Foundation (2026-07-19)");
  lines.push("// Do not edit by hand; regenerate via `node tools/interaction-inventory/codegen-control-ids.mjs --write`.");
  lines.push("");
  lines.push('import type { ControlIdRegistryEntry } from "../../../contracts/control-identity.types";');
  lines.push("");
  lines.push(`export const CONTROL_ID_REGISTRY_SCHEMA_VERSION = ${stringifyConst(registry.schemaVersion)};`);
  lines.push(`export const CONTROL_ID_REGISTRY_GENERATED_AT = ${stringifyConst(registry.generatedAt)};`);
  lines.push(`export const CONTROL_ID_REGISTRY_INVENTORY_SHA256 = ${stringifyConst(registry.generatedFrom.inventorySha256)};`);
  lines.push(`export const CONTROL_ID_REGISTRY_SCREENGRAPH_SHA256 = ${stringifyConst(registry.generatedFrom.screenGraphSha256)};`);
  lines.push(`export const CONTROL_ID_REGISTRY_TOTAL_ENTRIES = ${registry.totals.candidates};`);
  lines.push(`export const CONTROL_ID_REGISTRY_UNIQUE_CONTROL_IDS = ${registry.totals.uniqueControlIds};`);
  lines.push("");
  lines.push("export const CONTROL_ID_ENTRIES: readonly ControlIdRegistryEntry[] = Object.freeze([");
  for (const entry of registry.entries) {
    lines.push(`  ${stringifyConst(entry)},`);
  }
  lines.push("]);");
  lines.push("");
  lines.push("export const CONTROL_ID_LOOKUP: Readonly<Record<string, ControlIdRegistryEntry>> = Object.freeze(");
  lines.push("  Object.fromEntries(CONTROL_ID_ENTRIES.map((entry) => [entry.controlId, entry])),");
  lines.push(");");
  lines.push("");
  lines.push("export const CONTROL_ID_SET: ReadonlySet<string> = Object.freeze(new Set(CONTROL_ID_ENTRIES.map((entry) => entry.controlId)));");
  lines.push("");
  // R1.1: logical identity lookup maps. entityKey -> entries sharing that
  // entity (cross route/state/viewport). controlKey -> entries sharing that
  // controlKey (cross viewport, within a single route/state).
  lines.push("export const ENTITY_KEY_LOOKUP: Readonly<Record<string, readonly ControlIdRegistryEntry[]>> = Object.freeze(");
  lines.push("  Object.fromEntries(");
  lines.push("    Object.entries(");
  lines.push("      CONTROL_ID_ENTRIES.reduce<Record<string, ControlIdRegistryEntry[]>>((acc, entry) => {");
  lines.push("        (acc[entry.entityKey] ??= []).push(entry);");
  lines.push("        return acc;");
  lines.push("      }, {}),");
  lines.push("    ).map(([k, v]) => [k, Object.freeze(v)] as const),");
  lines.push("  ),");
  lines.push(");");
  lines.push("export const ENTITY_KEY_SET: ReadonlySet<string> = Object.freeze(new Set(CONTROL_ID_ENTRIES.map((entry) => entry.entityKey)));");
  lines.push("export const CONTROL_KEY_LOOKUP: Readonly<Record<string, readonly ControlIdRegistryEntry[]>> = Object.freeze(");
  lines.push("  Object.fromEntries(");
  lines.push("    Object.entries(");
  lines.push("      CONTROL_ID_ENTRIES.reduce<Record<string, ControlIdRegistryEntry[]>>((acc, entry) => {");
  lines.push("        (acc[entry.controlKey] ??= []).push(entry);");
  lines.push("        return acc;");
  lines.push("      }, {}),");
  lines.push("    ).map(([k, v]) => [k, Object.freeze(v)] as const),");
  lines.push("  ),");
  lines.push(");");
  lines.push("export const CONTROL_KEY_SET: ReadonlySet<string> = Object.freeze(new Set(CONTROL_ID_ENTRIES.map((entry) => entry.controlKey)));");
  lines.push("");
  lines.push(`export const CONTROL_ID_REGISTRY_UNIQUE_ENTITY_KEYS = ${registry.totals.uniqueEntityKeys};`);
  lines.push(`export const CONTROL_ID_REGISTRY_UNIQUE_CONTROL_KEYS = ${registry.totals.uniqueControlKeys};`);
  lines.push("");
  lines.push("export function getControlIdEntry(controlId: string): ControlIdRegistryEntry | undefined {");
  lines.push("  return CONTROL_ID_LOOKUP[controlId];");
  lines.push("}");
  lines.push("");
  lines.push("export function isKnownControlId(controlId: string): boolean {");
  lines.push("  return CONTROL_ID_SET.has(controlId);");
  lines.push("}");
  lines.push("");
  // R1.1: logical identity accessors.
  lines.push("export function getEntriesByEntityKey(entityKey: string): readonly ControlIdRegistryEntry[] {");
  lines.push("  return ENTITY_KEY_LOOKUP[entityKey] ?? [];");
  lines.push("}");
  lines.push("export function isKnownEntityKey(entityKey: string): boolean {");
  lines.push("  return ENTITY_KEY_SET.has(entityKey);");
  lines.push("}");
  lines.push("export function getEntriesByControlKey(controlKey: string): readonly ControlIdRegistryEntry[] {");
  lines.push("  return CONTROL_KEY_LOOKUP[controlKey] ?? [];");
  lines.push("}");
  lines.push("export function isKnownControlKey(controlKey: string): boolean {");
  lines.push("  return CONTROL_KEY_SET.has(controlKey);");
  lines.push("}");
  lines.push("");
  return `${lines.join("\n")}\n`;
}

function buildDomSelectorsArtifact(registry) {
  const byRoute = {};
  for (const entry of registry.entries) {
    if (!byRoute[entry.route]) byRoute[entry.route] = [];
    byRoute[entry.route].push({
      // R1.1: include logical identity (entityKey, controlKey) alongside
      // the DOM occurrence tracking id (controlId).
      entityKey: entry.entityKey,
      controlKey: entry.controlKey,
      controlId: entry.controlId,
      selectorSha256: entry.source.selectorSha256,
      dataControlId: entry.controlId,
      state: entry.state,
      viewport: entry.viewport,
      role: entry.role,
      family: entry.family,
      mappingStatus: entry.mappingStatus,
    });
  }
  for (const route of Object.keys(byRoute)) {
    byRoute[route].sort((a, b) => a.controlId.localeCompare(b.controlId));
  }
  return {
    schemaVersion: registry.schemaVersion,
    generatedAt: registry.generatedAt,
    generatedFrom: {
      ...registry.generatedFrom,
      codegenPath: "tools/interaction-inventory/codegen-control-ids.mjs",
    },
    totals: {
      routes: Object.keys(byRoute).length,
      entries: registry.entries.length,
      uniqueControlIds: registry.totals.uniqueControlIds,
      uniqueEntityKeys: registry.totals.uniqueEntityKeys,
      uniqueControlKeys: registry.totals.uniqueControlKeys,
    },
    byRoute,
  };
}

function buildScreenGraphBindingsArtifact(registry) {
  const entries = registry.entries.map((entry) => ({
    // R1.1: include logical identity (entityKey, controlKey).
    entityKey: entry.entityKey,
    controlKey: entry.controlKey,
    controlId: entry.controlId,
    candidateKey: entry.source.candidateKey,
    routeId: entry.route,
    state: entry.state,
    viewport: entry.viewport,
    componentInstanceId: entry.screenGraphBinding.componentInstanceId,
    componentType: entry.screenGraphBinding.componentType,
    bindingStatus: entry.screenGraphBinding.bindingStatus,
    uiEvent: entry.source.uiEvent,
  }));
  entries.sort((a, b) => a.controlId.localeCompare(b.controlId));
  return {
    schemaVersion: registry.schemaVersion,
    generatedAt: registry.generatedAt,
    generatedFrom: {
      ...registry.generatedFrom,
      codegenPath: "tools/interaction-inventory/codegen-control-ids.mjs",
    },
    totals: {
      totalControls: entries.length,
      bound: entries.filter((e) => e.bindingStatus === "bound").length,
      unresolved: entries.filter((e) => e.bindingStatus === "unresolved").length,
      pendingFigmaJoin: entries.filter((e) => e.bindingStatus === "pending-figma-join").length,
      uniqueComponentInstances: new Set(entries.filter((e) => e.componentInstanceId).map((e) => e.componentInstanceId)).size,
    },
    entries,
  };
}

function writeCodegenArtifacts() {
  const registry = readJson(CONTROL_ID_REGISTRY_PATH);
  const outputs = [
    [CODEGEN_OUTPUT_PATHS.typescriptTypes, buildTypescriptArtifact(registry)],
    [CODEGEN_OUTPUT_PATHS.domSelectors, formatJson(buildDomSelectorsArtifact(registry))],
    [CODEGEN_OUTPUT_PATHS.screenGraphBindings, formatJson(buildScreenGraphBindingsArtifact(registry))],
  ];
  for (const [relativePath, value] of outputs) {
    const absolutePath = join(REPO_ROOT, relativePath);
    mkdirSync(dirname(absolutePath), { recursive: true });
    writeFileSync(absolutePath, value);
  }
  return outputs.map(([relativePath]) => relativePath);
}

function checkCodegenArtifacts() {
  const registry = readJson(CONTROL_ID_REGISTRY_PATH);
  const expected = [
    [CODEGEN_OUTPUT_PATHS.typescriptTypes, buildTypescriptArtifact(registry)],
    [CODEGEN_OUTPUT_PATHS.domSelectors, formatJson(buildDomSelectorsArtifact(registry))],
    [CODEGEN_OUTPUT_PATHS.screenGraphBindings, formatJson(buildScreenGraphBindingsArtifact(registry))],
  ];
  for (const [relativePath, expectedValue] of expected) {
    const absolutePath = join(REPO_ROOT, relativePath);
    if (!existsSync(absolutePath)) {
      throw new Error(`missing codegen artifact: ${relativePath}`);
    }
    if (readFileSync(absolutePath, "utf8") !== expectedValue) {
      throw new Error(`codegen artifact drift: ${relativePath}; run node tools/interaction-inventory/codegen-control-ids.mjs --write`);
    }
  }
  return true;
}

const mode = process.argv[2];
if (!["--write", "--check"].includes(mode) || process.argv.length !== 3) {
  console.error("usage: node tools/interaction-inventory/codegen-control-ids.mjs --write|--check");
  process.exitCode = 2;
} else if (mode === "--write") {
  const paths = writeCodegenArtifacts();
  console.log(`[control-identity-codegen] wrote ${paths.length} artifacts`);
  for (const path of paths) console.log(`[control-identity-codegen] wrote ${path}`);
} else {
  checkCodegenArtifacts();
  console.log(`[control-identity-codegen] checked; artifacts byte-stable`);
}
